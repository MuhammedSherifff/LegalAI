from legal_agent.citations import check, extract_citations

CASES = [
    ("وفقا للمادة 163 يكون الخطأ سببا للضرر", {"163"}),
    ("(المادة 163)", {"163"}),
    ("المادة (163)", {"163"}),
    ("المادة (١٦٣) من القانون المدني", {"163"}),
    ("(مادة ١٦٣)", {"163"}),
    ("م 163", {"163"}),
    ("م. ١٦٣", {"163"}),
    ("مادة رقم 15", {"15"}),
    ("المادة 163 والمادة 164", {"163", "164"}),
    ("المادة 163 و164", {"163", "164"}),
    ("المواد 5 من القانون", {"5"}),
    ("المادة 163.1", {"163"}),
    ("لا توجد إشارة إلى نصوص هنا", set()),
    ("هذه الحالة لا تحدد أي مادة", set()),
    ("المواد من 5 إلى 10 ملغاة", set()),
]


def test_extract_variants():
    for text, expected in CASES:
        assert extract_citations(text) == expected, text


def test_check_flags_fabricated():
    assert check("نص المادة 999 يجيز ذلك", {"163", "164"}) == {"999"}


def test_check_passes_grounded():
    assert check("وفقا للمادة 163 والمادة (164)", {"163", "164"}) == set()
